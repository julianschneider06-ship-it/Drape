import { readFileSync } from "node:fs";
import { buildCatalogue, unpackSnapshot } from "../../src/outfits/catalogue";
import { compose, newSession } from "../../src/outfits/compose";
import { alternativesFor } from "../../src/outfits/compose-alts";
import { BanState } from "../../src/outfits/ban";
import { outfitTags } from "../../src/outfits/tags";
const ms = () => performance.now();
const b64 = readFileSync(process.env.SNAP!, "utf8");
let t = ms(); const snap = unpackSnapshot(b64); console.log("gunzip+parse", (ms() - t).toFixed(0));
t = ms(); const cat = buildCatalogue(snap); console.log("build", (ms() - t).toFixed(0));
t = ms(); const r = compose(cat, { gender: "men", taste: null }, new BanState(), 6, newSession()); console.log("first compose", (ms() - t).toFixed(0));
t = ms(); const eff = r.ban.effective(cat, "men"); r.outfits.map((o) => alternativesFor(cat, "men", o, eff, null)); console.log("first alternatives", (ms() - t).toFixed(0));
t = ms(); r.outfits.map((o) => outfitTags(cat, { pieces: o.ids.map((i) => cat.byId.get(i)!), accs: [], bucket: o.bucket })); console.log("first tags", (ms() - t).toFixed(0));
t = ms(); compose(cat, { gender: "men", taste: null }, new BanState(), 6, newSession()); console.log("second compose", (ms() - t).toFixed(0));
